"""Generate the page theme, src/tokens.css. Run from any directory; --check writes nothing."""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_brand(root=ROOT):
    data = json.loads((root / "brand/tokens.json").read_text())
    if data["mascot"] not in ("cat", "dog"):
        raise ValueError("mascot must be cat or dog")
    for theme in [data["light"], data["dark"], *data["accents"].values()]:
        for key, value in theme.items():
            if (not re.fullmatch(r"[a-z][a-z0-9-]*", key)
                    or not isinstance(value, str) or not value
                    or re.search(r"[;{}<>\r\n]|url\s*\(", value, re.I)):
                raise ValueError("Invalid CSS token: " + key)
    if not set(data["dark"]) <= set(data["light"]):
        raise ValueError("A dark token lacks a light default")
    for name, theme in data["accents"].items():
        if not re.fullmatch(r"[a-z]+", name) or not set(theme) <= set(data["light"]):
            raise ValueError("Invalid accent: " + name)
    # an accent may carry its own dark values, so a dark page keeps its links and buttons readable
    for name, theme in data.get("accents-dark", {}).items():
        if name not in data["accents"] or not set(theme) <= set(data["light"]):
            raise ValueError("Invalid dark accent: " + name)
        for key, value in theme.items():
            if not isinstance(value, str) or not value or re.search(r"[;{}<>\r\n]|url\s*\(", value, re.I):
                raise ValueError("Invalid CSS token: " + key)
    return data


def css(data):
    def block(selector, values, dark=False):
        lines = [f"  --{k}: {v};" for k, v in values.items()]
        if dark:
            lines.append("  color-scheme: dark;")
        return selector + " {\n" + "\n".join(lines) + "\n}\n"
    text = "/* Generated by brand/generate_tokens.py; edit brand/tokens.json. */\n"
    swatches = {"swatch-violet": data["light"]["accent"], **{"swatch-" + name: values["accent"] for name, values in data["accents"].items()}}
    text += block(":root", {**data["light"], **swatches})
    text += '@media (prefers-color-scheme: dark) {\n' + block(':root:not([data-theme="light"])', data["dark"], True) + '}\n'
    text += block(':root[data-theme="dark"]', data["dark"], True)
    text += "".join(block(f':root[data-accent="{k}"]', v) for k, v in data["accents"].items())
    for k, v in data.get("accents-dark", {}).items():
        text += '@media (prefers-color-scheme: dark) {\n' + block(f':root:not([data-theme="light"])[data-accent="{k}"]', v) + '}\n'
        text += block(f':root[data-theme="dark"][data-accent="{k}"]', v)
    return text


def generate(root, check=False):
    data = read_brand(root)
    outputs = {"src/tokens.css": css(data)}
    stale = []
    for name, value in outputs.items():
        path = root / name
        if path.is_file() and path.read_text() == value:
            continue
        if check:
            stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    return stale


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    stale = generate(ROOT, parser.parse_args().check)
    if stale:
        sys.exit("Regenerate with python3 brand/generate_tokens.py: " + ", ".join(stale))
