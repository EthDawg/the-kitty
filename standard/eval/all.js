#!/usr/bin/env node
/* Everything, in one command. Builds nothing itself: run `node standard/world/build.js` first.
   node standard/eval/all.js            print the scoreboard
   node standard/eval/all.js --write    also rewrite SCOREBOARD.md, locked.json and append history.jsonl
   node standard/eval/all.js --check    fail if a locked number moved or a law, rung or household fails */
"use strict";
const fs = require("fs"), path = require("path");
const { spawnSync } = require("child_process");
const { hash64, stableStringify } = require("../engine/util");

const args = process.argv.slice(2);
const here = __dirname;
const lockedPath = path.join(here, "locked.json");

function replay(mode) {
  process.argv = [process.argv[0], "run.js", "--mode", mode];
  delete require.cache[require.resolve("./run")];
  const { run } = require("./run");
  return run();
}
function households() {
  const r = spawnSync("node", ["--test", path.join(here, "households", "test.js")], { encoding: "utf8" });
  const pass = +(r.stdout.match(/^# pass (\d+)/m) || [0, 0])[1], fail = +(r.stdout.match(/^# fail (\d+)/m) || [0, 0])[1];
  return { pass, fail };
}
function lockFrom(L, s) {
  const lock = { bundle_hash: L.bundleHash, as_of: L.asOf, events: L.events.length, postings: L.postings.length, net_worth_by_month: Object.fromEntries(L.netWorth.map((r) => [r.month, r.total])), cash_net_by_month: Object.fromEntries(L.cash.map((r) => [r.month, r.net])) };
  if (L.tax) lock.tax = Object.fromEntries(L.tax.estimates.map((e) => [`${e.person} ${e.fy}`, e.taxable_income_cents]));
  lock.fingerprint = hash64(stableStringify(lock));
  return lock;
}
function main() {
  const t0 = Date.now();
  const back = replay("returning"), fresh = replay("new");
  const { main: ladder } = require("./ladder");
  const log = console.log; console.log = () => {};
  const rungs = ladder();
  console.log = log;
  const { parity } = require("./sheet-parity");
  const par = parity();
  const hh = households();
  const coldPath = path.join(here, "coldstart.json");
  const cold = fs.existsSync(coldPath) ? JSON.parse(fs.readFileSync(coldPath, "utf8")) : null;

  const s = back.s, f = fresh.s;
  const row = (r) => `| ${r.name} | ${r.exact} of ${r.checked} | ${r.pct}% |`;
  const lawsLine = Object.entries(s.laws).map(([k, v]) => `${k} ${v.fail ? `**fail ×${v.fail}**` : v.gap ? `gap ×${v.gap}` : v.open && !v.pass ? "open" : v.pass ? "pass" : "skip"}`).join(", ");
  const md = [
    "# Scoreboard", "", "Generated by `node standard/eval/all.js --write`. Davies is fictional. Sheet oracle figures were computed by Google Sheets formulas, not by this engine.", "",
    `Replay: ${s.run.files} files, ${s.run.observations} observations, ${s.run.events} events, ${s.run.postings} postings. Ingest ${s.run.ingest_s}s, rebuild ${s.run.rebuild_s}s. Bundle \`${s.run.bundle_hash}\`.`, "",
    "## A returning household", "", "Keeps decisions, rules and recipes.", "", "| Check | Exact | |", "|---|---|---|", ...s.sections.map(row), "", `Laws: ${lawsLine}.`, "", `Items for a person: ${s.review.items}.`, "",
    "## A new household", "", "Public dictionary and public recipes only. No decisions, no rules.", "", "| Check | Exact | |", "|---|---|---|", ...f.sections.map(row), "", `Items for a person: ${f.review.items}.`, "",
    "## The ladder", "", ...rungs.map((r) => `- ${r.ok ? "holds" : "**breaks**"}: ${r.name}`), "", `${rungs.filter((r) => r.ok).length} of ${rungs.length} rungs hold. A presentation rung holds when the bundle hash is unchanged. A semantic rung holds when the right alarm rings in the right place.`, "",
    "## Households", "", `${hh.pass} small lives, written as observations, each with its truth beside it: ${hh.fail} fail. These prove the model's truth, not file reading.`, "",
    "## The Sheet", "", par.skipped ? `Skipped: ${par.skipped}.` : `Workbook formulas recalculated in LibreOffice against the engine: ${par.exact} of ${par.checked} cells exact.`, "",
    ...(cold ? ["## Cold start", "", `A cheap model (${cold.model}) wrote importers from one sample and the recipe spec: ${cold.passed} of ${cold.families} families passed the gate on the first try or after one repair; the run stopped at its US$12 cap with 8 of 58 families untried. ${cold.tokens_in} tokens in, ${cold.tokens_out} out, about US$${cold.usd}. The gate refused the other ${cold.families - cold.passed}, so none reached a ledger. ${cold.second_protocol ? cold.second_protocol.note : ""} Golden recipes passed for all 58. The second household pays nothing: recipes are cached by fingerprint.`, ""] : []),
  ].join("\n");
  const lock = lockFrom(back.L, s);
  console.log(md);
  console.log(`\n(${((Date.now() - t0) / 1000).toFixed(1)}s)`);
  if (args.includes("--write")) {
    fs.writeFileSync(path.join(here, "SCOREBOARD.md"), md);
    fs.writeFileSync(lockedPath, JSON.stringify(lock, null, 1) + "\n");
    fs.appendFileSync(path.join(here, "history.jsonl"), JSON.stringify({ at: new Date().toISOString().slice(0, 10), ...s.run, review_returning: s.review.items, review_new: f.review.items, rungs: rungs.filter((r) => r.ok).length, households: hh.pass, sheet: par.exact || null, cold_tokens: cold ? cold.tokens_in + cold.tokens_out : null }) + "\n");
  }
  if (args.includes("--check")) {
    const problems = [];
    if (rungs.some((r) => !r.ok)) problems.push("a ladder rung broke");
    if (hh.fail) problems.push(`${hh.fail} households fail`);
    if (par.misses && par.misses.length) problems.push("the sheet disagrees with the engine");
    if (fs.existsSync(lockedPath)) { const was = JSON.parse(fs.readFileSync(lockedPath, "utf8")); if (was.fingerprint !== lock.fingerprint) problems.push(`locked numbers moved: ${was.fingerprint} to ${lock.fingerprint}. If this is intended, run --write and say why in the commit.`); }
    if (problems.length) { console.error(`\n${problems.join("\n")}`); process.exitCode = 1; }
  }
}
main();
